// Writes the release data the site needs from the repo's vX.Y.Z tags:
//   src/generated/release.json        latest version for the download buttons
//   src/content/docs/changelog.md     every release's notes
// Both files are gitignored and regenerated on every build.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { REPO_URL, compareLink, notes, releaseTags } from '../../.github/scripts/changelog.mjs';

const site = join(dirname(fileURLToPath(import.meta.url)), '..');
const root = join(site, '..');

let tags = [];
try {
	tags = releaseTags(root);
} catch (err) {
	console.warn(`releases: could not read git tags (${err.message.trim()})`);
}

const latest = tags[0] ?? null;
const release = latest
	? { version: latest.tag.replace(/^v/, ''), tag: latest.tag, date: latest.date }
	: { version: null, tag: null, date: null };

mkdirSync(join(site, 'src/generated'), { recursive: true });
writeFileSync(join(site, 'src/generated/release.json'), `${JSON.stringify(release, null, '\t')}\n`);

const formatDate = (date) =>
	new Date(`${date}T00:00:00Z`).toLocaleDateString('en-US', {
		year: 'numeric',
		month: 'long',
		day: 'numeric',
		timeZone: 'UTC',
	});

const sections = tags.map(({ tag, date }, i) => {
	const previous = tags[i + 1]?.tag ?? '';
	let body;
	try {
		body = notes(root, previous, tag, { headingLevel: 3 });
	} catch {
		// Shallow clones don't have the history between tags.
		body = `See the [${tag} release](${REPO_URL}/releases/tag/${tag}).`;
	}
	return [
		`## ${tag}`,
		`<p class="release-meta">Released ${formatDate(date)} · <a href="${REPO_URL}/releases/tag/${tag}">Downloads</a></p>`,
		body,
		compareLink(previous, tag),
	].join('\n\n');
});

const page = `---
title: Changelog
description: What changed in each Scraper release.
tableOfContents:
  maxHeadingLevel: 2
editUrl: false
lastUpdated: false
---

<!-- Generated by site/scripts/releases.mjs from the git tags. Do not edit. -->

Every release is built and published from \`main\`; the version is picked from
the [Conventional Commits](https://www.conventionalcommits.org/) since the
previous release. Downloads for each version are on its
[GitHub release](${REPO_URL}/releases).

${sections.length ? sections.join('\n\n') : `No release information was available when this page was built. See [GitHub releases](${REPO_URL}/releases).`}
`;

writeFileSync(join(site, 'src/content/docs/changelog.md'), page);
console.log(`releases: ${tags.length} releases, latest ${release.tag ?? 'none'}`);
